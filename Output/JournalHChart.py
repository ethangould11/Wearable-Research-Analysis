"""Reusable horizontal bar chart exporter for wearable research figures."""

from pathlib import Path
import os
import os
import re
import tempfile

# Keep the font cache in a writable, reusable location for direct question
# runs as well as the all-question runner.
cache_dir = Path(tempfile.gettempdir()) / "wearable-research-matplotlib"
cache_dir.mkdir(parents=True, exist_ok=True)
os.environ.setdefault("MPLCONFIGDIR", str(cache_dir))

import matplotlib

# Reports are generated as files, not interactive chart windows. The Agg
# backend works from VS Code, terminals, and headless environments alike.
matplotlib.use("Agg")
import matplotlib.pyplot as plt
import pandas as pd
from matplotlib.ticker import PercentFormatter
from docx import Document
from docx.shared import Inches


def journal_h_chart(
    data: pd.DataFrame,
    category: str,
    value: str,
    counts: str | None = None,
    title: str = "Wearable Device Use Among College Students",
    xlabel: str = "Percentage of wearable users (%)",
    note: str | None = None,
    filename: str = "Wearable_Device_Popularity_Bar_Chart",
    percentage: bool = True,
    word_document: str | Path | None = None,
    image_width_inches: float = 6.0,
) -> tuple[Path, Path]:
    """Save a publication-oriented horizontal bar chart as PNG and vector PDF.

    For percentage charts, `value` must be on a 0–100 scale.
    When `word_document` is provided, insert the chart into the existing
    Word document generated by JournalTable. `counts` adds bar labels.
    """
    required = [category, value] + ([counts] if counts else [])
    missing = [column for column in required if column not in data.columns]
    if missing:
        raise KeyError(f"Missing chart columns: {missing}")

    chart = data.loc[:, required].copy()
    if chart.empty:
        raise ValueError("Cannot plot an empty table")
    chart[value] = pd.to_numeric(chart[value], errors="raise")
    if chart[value].isna().any() or (chart[value] < 0).any():
        raise ValueError("Chart values must be nonnegative and nonmissing")
    if percentage and (chart[value] > 100).any():
        raise ValueError("Percentages must be on a 0–100 scale")
    if counts:
        chart[counts] = pd.to_numeric(chart[counts], errors="raise")
        if chart[counts].isna().any():
            raise ValueError("Counts must be nonmissing")
    chart = chart.sort_values(value, ascending=True)

    fig, ax = plt.subplots(figsize=(8.5, max(3.5, 0.5 * len(chart) + 1.5)))
    bars = ax.barh(chart[category].astype(str), chart[value], color="#356B86")
    upper = 110 if percentage else max(1, chart[value].max() * 1.22)
    ax.set_xlim(0, upper)
    ax.set_xlabel(xlabel)
    ax.set_title(title, loc="left", fontsize=12, fontweight="bold", pad=14)
    if percentage:
        ax.xaxis.set_major_formatter(PercentFormatter(xmax=100, decimals=0))
    ax.grid(axis="x", alpha=0.18)
    ax.set_axisbelow(True)
    ax.tick_params(axis="y", length=0)
    for side in ("top", "right", "left"):
        ax.spines[side].set_visible(False)

    for bar, (_, row) in zip(bars, chart.iterrows()):
        label = f"{row[value]:.1f}%" if percentage else f"{row[value]:g}"
        if counts:
            label += f" (n={int(row[counts])})"
        ax.text(bar.get_width() + upper * 0.01,
                bar.get_y() + bar.get_height() / 2,
                label, va="center", ha="left", fontsize=9)

    if note:
        fig.text(0.12, 0.025, note, fontsize=8, ha="left", va="bottom", wrap=True)
    fig.tight_layout(rect=(0, 0.10 if note else 0, 1, 1))

    output_dir = Path(__file__).resolve().parent
    output_dir.mkdir(parents=True, exist_ok=True)
    safe_name = re.sub(r"[^A-Za-z0-9_-]+", "_", filename).strip("_") or "chart"
    png_path = output_dir / f"{safe_name}.png"
    pdf_path = output_dir / f"{safe_name}.pdf"
    fig.savefig(png_path, dpi=300, bbox_inches="tight", facecolor="white")
    fig.savefig(pdf_path, bbox_inches="tight", facecolor="white")
    plt.close(fig)
    print(f"Horizontal bar chart saved: {png_path}")
    print(f"Vector PDF saved: {pdf_path}")

    if word_document is not None:
        document_path = Path(word_document)
        if not document_path.is_file():
            raise FileNotFoundError(
                f"Table document not found: {document_path}. "
                "Pass the exact DOCX path generated by journal_table()."
            )
        doc = Document(str(document_path))
        doc.add_paragraph()
        caption = doc.add_paragraph(style="Caption")
        caption.add_run(f"Figure. {title}")
        doc.add_picture(str(png_path), width=Inches(image_width_inches))
        if note:
            doc.add_paragraph(f"Note. {note}")
        doc.save(str(document_path))
        print(f"Figure embedded in Word document: {document_path}")

    return png_path, pdf_path

# Backward-compatible alias for older analysis imports.
JournalHChart = journal_h_chart
